"""
Deep Picard regression for Nash equilibria of games with private information.

This module implements the method of notes/method.tex (referred to below as "the note"). Player i
chooses a control u^i adapted to the filtration F^i generated by its own observations O^i. In the
quadratic case, the first order condition of player i is

    u^i_t = (1 / 2 a_i) E[ Lambda^i_t | F^i_t ],                       (note, Section 1.2)

where Lambda^i_t depends on the future state and on the controls of all players. The equilibrium is
the fixed point u = Psi(u) of the operator that maps the controls to the right-hand side for every
player (note, Section 1.3). It is computed by the damped Picard iteration

    u^(k+1) = (1 - rho) u^(k) + rho Psi(u^(k)),                         (note, Section 1.5)

in which each conditional expectation is approximated by a recurrent network of the player's own
observed path, fitted by minimizing a mean squared error over simulated paths (note, Section 1.4).

Contents:
    Control                  the network N^i of player i
    Solver                   the damped Picard iteration, open loop and closed loop
    gradient_play            an alternative closed-loop solver: each player descends its own realised cost
    linear_equilibrium       the same iteration among controls linear in the observed path (a baseline)
    first_order_residual     a check of the first order condition at the computed equilibrium

Games implement games.base.Game. Costs are minimized: the cost of player i is minus the reward J^i
of the note.
"""

import copy
import time

import numpy as np
import torch
import torch.nn as nn

# The validation paths, on which every method and every exact reference is compared.
VALIDATION_SEED = 7
N_VALIDATION = 2048


# ==============================================================================
# Utilities
# ==============================================================================

def report(message: str):
    """Prints a progress line immediately (unbuffered, for cluster logs)."""
    print(message, flush=True)


def use_device(name: str = None) -> str:
    """
    Sets the default torch device.

    Args:
        name: 'cuda', 'mps' or 'cpu'. Default: the first available in that order.

    Returns:
        The name of the device set.
    """
    if name is None:
        name = 'cuda' if torch.cuda.is_available() else 'mps' if torch.backends.mps.is_available() else 'cpu'
    torch.set_default_device(name)
    return name


def validation_paths(game) -> dict:
    """Noise of the validation paths of a game: N_VALIDATION paths from VALIDATION_SEED."""
    return game.sample(N_VALIDATION, VALIDATION_SEED)


def relative_l2(estimate: torch.Tensor, reference: torch.Tensor) -> float:
    """Relative L2 error ||estimate - reference|| / ||reference|| over all paths and times."""
    return float(((estimate - reference) ** 2).mean().sqrt() / (reference ** 2).mean().sqrt())


def format_errors(controls: list, reference: list) -> str:
    """Relative L2 errors per player, formatted for a log line."""
    return ' '.join(f'{relative_l2(c, r):.3f}' for c, r in zip(controls, reference))


def subset(noise: dict, index: torch.Tensor) -> dict:
    """The noise of the paths in index."""
    return {key: value[index] for key, value in noise.items()}


def mlp(n_in: int, n_out: int, width: int = 64) -> nn.Module:
    """Feedforward network with two hidden layers of the given width and tanh activations."""
    return nn.Sequential(nn.Linear(n_in, width), nn.Tanh(),
                         nn.Linear(width, width), nn.Tanh(),
                         nn.Linear(width, n_out))


class RunningAverage:
    """
    Average of the validation controls over Picard iterations (iterate averaging, note Section 1.5).

    The average over the last iterates is reported instead of the last iterate. It reduces the
    iteration-to-iteration fluctuation caused by the regression noise.
    """

    def __init__(self):
        self.value = None
        self.count = 0

    def add(self, controls: list):
        """Adds one iterate: a list of [M, N] tensors, one per player."""
        self.count += 1
        if self.value is None:
            self.value = [c.clone() for c in controls]
        else:
            self.value = [v + (c - v) / self.count for v, c in zip(self.value, controls)]


# ==============================================================================
# The control of one player
# ==============================================================================

class Control(nn.Module):
    """
    The network N^i of player i (note, Section 1.4).

    The control at t_j is a function of the observed path O^i on [0, t_j]:

        u^i_{t_j} = head( t_j, O^i_{t_j}, h_j ),

    where h_j is the state of a GRU that takes the increments of O^i over [t_0, t_1], ..., [t_{j-1}, t_j]
    as input, with h_0 = 0. Thus u^i_{t_j} is F^i_{t_j}-measurable. A player whose observation increments
    have dimension 0 has no GRU, and its control is a function of (t_j, O^i_{t_j}) only.
    """

    def __init__(self, observation_dim: int, increment_dim: int, width: int = 32):
        """
        Args:
            observation_dim: Dimension of the current observation O^i_t.
            increment_dim: Dimension of the observation increments (0 for no memory).
            width: Hidden size of the GRU. Default 32.
        """
        super().__init__()
        self.width = width if increment_dim > 0 else 0
        self.gru = nn.GRU(increment_dim, width, batch_first=True) if increment_dim > 0 else None
        self.head = mlp(1 + observation_dim + self.width, 1)

    def memory(self, increments: torch.Tensor):
        """
        GRU states before each step, from a whole path of increments.

        Args:
            increments: Observation increments [M, N, increment_dim].

        Returns:
            Tensor [M, N, width] whose entry j is h_j, the state after the increments 0, ..., j - 1
            (zero at j = 0), or None without a GRU.
        """
        if self.gru is None:
            return None
        states, _ = self.gru(increments)
        return torch.cat([torch.zeros(increments.shape[0], 1, self.width), states[:, :-1]], 1)

    def forward(self, t: torch.Tensor, observation: torch.Tensor, memory) -> torch.Tensor:
        """
        Args:
            t: Time [M, 1].
            observation: Current observation [M, observation_dim].
            memory: GRU state h_j [M, width], or None.

        Returns:
            Controls [M].
        """
        inputs = [t, observation] + ([memory] if memory is not None else [])
        return self.head(torch.cat(inputs, -1)).squeeze(-1)


# ==============================================================================
# The damped Picard iteration
# ==============================================================================

class Solver:
    """
    Damped Picard iteration over all players (note, Algorithm 1).

    Each iteration k:
        1. Forward simulation. Simulate M paths of the game under the current controls u^(k).
        2. Targets. Evaluate Lambda^i / (2 a_i) along each path for every player i, by differentiating
           the realised cost with respect to the player's own control (Solver.targets).
        3. Regression. Fit the network of each player to the damped target
               (1 - rho) u^{i,(k)} + (rho / 2 a_i) Lambda^i
           by minimizing the mean squared error over the paths, with the player's own observed path as
           the only input (Solver.fit).
    The validation controls are averaged over the later iterations.

    Control variate. The targets contain the future noise of every player. With control_variate, a term
    sum_{j' >= j} decay^{j' - j} zeta^i(t_{j'}, X_{t_{j'}}) . dW_{j'} is subtracted from the target at
    t_j, with zeta^i a network of the full state fitted jointly with the control. Each increment dW_{j'}
    has zero conditional mean given the full state at t_{j'}, hence given F^i_{t_j}. The conditional
    expectation and the fixed point are therefore unchanged, and only the variance of the target drops.
    """

    def __init__(self, game, width: int = 32, damping: float = 0.6, steps: int = 1000, batch: int = 1024,
                 lr: float = 1e-3, n_paths: int = 8192, control_variate: bool = True, seed: int = 0):
        """
        Args:
            game: The game (games.base.Game).
            width: GRU width of every control. Default 32.
            damping: rho, the weight of the new target in the Picard step. Default 0.6.
            steps: Adam steps of each regression. Default 1000.
            batch: Minibatch size of the regression. Default 1024.
            lr: Learning rate of the regression. Default 1e-3.
            n_paths: Number M of training paths. Default 8192.
            control_variate: Whether to subtract the learned martingale term from the targets. Default True.
            seed: Seed of the network initialisation and of the training paths. Default 0.
        """
        torch.manual_seed(seed)
        self.game = game
        self.damping = damping
        self.steps = steps
        self.batch = batch
        self.lr = lr
        self.controls = [Control(game.observation_dims[i], game.increment_dims[i], width) for i in range(game.n_players)]
        self.control_variate = control_variate
        if control_variate:
            self.zetas = [mlp(1 + game.full_dim, game.noise_dim) for _ in range(game.n_players)]
            # Kernel of the martingale term: entry [j', j] = decay^(j' - j) for j' >= j, else 0.
            later, now = np.indices((game.N, game.N))
            self.cv_kernels = [torch.tensor(np.where(later >= now, decay ** (later - now), 0.0), dtype=torch.float32)
                               for decay in game.cv_decay]
        self.noise = game.sample(n_paths, 1 + 100 * seed)
        self.validation = validation_paths(game)
        self.t = torch.arange(game.N, dtype=torch.float32) * game.dt     # the grid t_0, ..., t_{N-1}

    # --------------------------------------------------------------------------
    # Step 1: forward simulation
    # --------------------------------------------------------------------------

    def simulate(self, noise: dict, fixed: dict = None, live=()):
        """
        Simulates the game on the given paths, by the Euler--Maruyama scheme with the controls given by
        the networks at each step (note, Section 1.4).

        Args:
            noise: Noise of M paths (game.sample).
            fixed: {player: controls [M, N]} for players whose controls are given instead of computed by
                their networks. Default none.
            live: Players whose network outputs keep the computational graph (for differentiation
                through the network). Other outputs are detached. Default none.

        Returns:
            state: The state paths (game.initial_state, filled in).
            controls: List of [M, N] tensors, one per player.
            increments: List of [M, N, increment_dim] observation increments of the players with a GRU
                that were not fixed, else None.
        """
        game = self.game
        M = next(iter(noise.values())).shape[0]
        fixed = fixed or {}
        state = game.initial_state(noise)
        hidden = [None if c.gru is None else torch.zeros(1, M, c.width) for c in self.controls]
        controls = [[] for _ in self.controls]
        increments = [[] for _ in self.controls]
        needs_graph = bool(live) or any(u.requires_grad for u in fixed.values())
        with torch.set_grad_enabled(needs_graph):
            for j in range(game.N):
                u = {}
                for i, control in enumerate(self.controls):
                    if i in fixed:
                        u[i] = fixed[i][:, j]
                    else:
                        memory = None if control.gru is None else hidden[i][0]
                        u[i] = control(self.t[j].expand(M, 1), game.observe(i, state, noise, j), memory)
                        if i not in live:
                            u[i] = u[i].detach()
                    controls[i].append(u[i])
                game.step(state, noise, u, j)
                # Feed the observation increments over [t_j, t_{j+1}] to the GRUs.
                for i, control in enumerate(self.controls):
                    if control.gru is not None and i not in fixed:
                        increment = game.increment(i, state, noise, j)
                        increments[i].append(increment)
                        hidden[i] = control.gru(increment[:, None], hidden[i])[1]
                        if i not in live:
                            hidden[i] = hidden[i].detach()
        controls = [torch.stack(c, 1) for c in controls]
        increments = [torch.stack(c, 1) if c else None for c in increments]
        return state, controls, increments

    # --------------------------------------------------------------------------
    # Step 2: targets
    # --------------------------------------------------------------------------

    def targets(self, noise: dict, controls: list, closed: bool = False) -> list:
        """
        Evaluates Lambda^i / (2 a_i) along each path for every player, the quantity inside the conditional
        expectation of the operator Psi (note, Section 1.3).

        The derivative of the realised reward is G^i = -2 a_i u^i + Lambda^i (note, Section 1.2), and the
        cost is minus the reward. Hence Lambda^i / (2 a_i) = u^i - (d cost / d u^i) / (2 a_i). The
        derivative is computed by automatic differentiation of the realised cost with respect to the
        player's own controls, in chunks of 4096 paths, and game.curvature(i) supplies 2 a_i dt.

        Args:
            noise: Noise of the paths.
            controls: Current controls, list of [M, N] tensors.
            closed: Open loop (default): the other players' controls are held fixed as processes.
                Closed loop: the other players act through their networks, so their controls respond to
                player i through their observations.

        Returns:
            List of [M, N] targets, one per player.
        """
        game = self.game
        M = controls[0].shape[0]
        all_targets = []
        for i in range(game.n_players):
            target = torch.zeros_like(controls[i])
            for start in range(0, M, 4096):
                index = torch.arange(start, min(start + 4096, M))
                part = subset(noise, index)
                own = controls[i][index].detach().clone().requires_grad_(True)
                if closed:
                    fixed = {i: own}
                    live = set(range(game.n_players)) - {i}
                else:
                    fixed = {j: (own if j == i else c[index].detach()) for j, c in enumerate(controls)}
                    live = ()
                state, used, _ = self.simulate(part, fixed, live)
                cost = game.cost(i, state, part, used).sum()
                gradient, = torch.autograd.grad(cost, own)
                target[index] = (own - gradient / game.curvature(i)).detach()
            all_targets.append(target)
        return all_targets

    # --------------------------------------------------------------------------
    # Step 3: regression
    # --------------------------------------------------------------------------

    def fit(self, noise: dict, state: dict, increments: list, targets: list, damping: float, players=None) -> float:
        """
        Fits the networks to the targets by minimizing a mean squared error (note, Section 1.4).

        For each player i, the loss is the mean over paths and times of

            | N^i(t_j, O^i_{[0, t_j]}; theta^i) - target^i_j |^2,

        minimized by Adam from the current parameters (warm start). With the control variate, damping
        times the martingale term is subtracted from the target, since the target is already damped by
        the same factor, and zeta^i is fitted jointly.

        Args:
            noise, state, increments: The simulated paths (Solver.simulate).
            targets: List of [M, N] targets, one per player.
            damping: Weight of the martingale term.
            players: Players to fit. Default all.

        Returns:
            The loss at the last step.
        """
        game = self.game
        M = targets[0].shape[0]
        players = range(game.n_players) if players is None else players
        observations = [torch.stack([game.observe(i, state, noise, j) for j in range(game.N)], 1)
                        for i in range(game.n_players)]
        t = self.t.expand(M, game.N)[..., None]
        parameters = [p for i in players for p in self.controls[i].parameters()]
        if self.control_variate:
            full_state = torch.cat([t, game.full_state(state, noise)], -1)
            dW = game.martingale_increments(noise)
            parameters += [p for i in players for p in self.zetas[i].parameters()]
        optimizer = torch.optim.Adam(parameters, lr=self.lr)
        for _ in range(self.steps):
            index = torch.randint(0, M, (self.batch,))
            loss = 0.0
            for i in players:
                control = self.controls[i]
                memory = control.memory(increments[i][index]) if control.gru is not None else None
                target = targets[i][index]
                if self.control_variate:
                    martingale = (self.zetas[i](full_state[index]) * dW[index]).sum(-1) @ self.cv_kernels[i]
                    target = target - damping * martingale
                prediction = control(t[index], observations[i][index], memory)
                loss = loss + ((prediction - target) ** 2).mean()
            optimizer.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(parameters, 5.0)
            optimizer.step()
        return float(loss.detach())

    # --------------------------------------------------------------------------
    # The iteration
    # --------------------------------------------------------------------------

    def run(self, iterations: int, average_from: int = 4, reference: list = None, closed: bool = False, log=report):
        """
        Runs the damped Picard iteration (note, Algorithm 1).

        Args:
            iterations: Number K of iterations.
            average_from: First iteration included in the average of the validation controls. Default 4.
            reference: Reference validation controls, list of [M, N] tensors, for the error log. Default none.
            closed: Whether to use the closed-loop targets. Default False (open loop).
            log: Function that receives one progress line per iteration.

        Returns:
            controls: The averaged validation controls, list of [M, N] tensors.
            history: Per iteration, the relative L2 error of each player's last iterate against reference.
        """
        average = RunningAverage()
        history = []
        start = time.time()
        for k in range(iterations):
            state, controls, increments = self.simulate(self.noise)
            targets = self.targets(self.noise, controls, closed)
            damped = [(1 - self.damping) * u + self.damping * target for u, target in zip(controls, targets)]
            loss = self.fit(self.noise, state, increments, damped, self.damping)
            _, validation, _ = self.simulate(self.validation)
            if k >= average_from:
                average.add(validation)
            message = f'iteration {k:2d}  loss {loss:.2e}'
            if reference is not None:
                history.append([relative_l2(v, r) for v, r in zip(validation, reference)])
                message += '  error ' + format_errors(validation, reference)
                if average.value is not None:
                    message += '  averaged ' + format_errors(average.value, reference)
            log(message + f'  ({time.time() - start:.0f}s)')
        return (average.value or validation), history


