"""
Deep Picard regression for open-loop Nash equilibria of games with private information.

This module implements the method of notes/method.tex (referred to below as "the note"). Player i chooses a
control uⁱ adapted to the filtration ℱⁱ generated by its own observations Oⁱ. In the quadratic case, the first
order condition of player i is

    uⁱ_t = (1 / 2 aᵢ) 𝔼[ Λⁱ_t | ℱⁱ_t ],

where Λⁱ_t depends on the future state and on the controls of all players. The equilibrium is the fixed
point u = Ψ(u) of the operator that maps the controls to the right-hand side for every player. It is computed
by the damped Picard iteration

    u⁽ᵏ⁺¹⁾ = (1 - ρ) u⁽ᵏ⁾ + ρ Ψ(u⁽ᵏ⁾),

in which each conditional expectation is approximated by a recurrent network of the player's own observed path,
fitted by minimizing a mean squared error over simulated paths.

Contents:
    Solver                   the damped Picard iteration
    first_order_residual     a check of the first order condition at the computed equilibrium
"""

import copy
import math
import time

import torch
import torch.nn as nn

from .control import Control
from .control_variate import ControlVariate
from .utils import relative_l2, validation_paths


class Solver:
    """
    Damped Picard iteration over all players, as in the algorithm of the note.

    Each iteration k:
        1. Forward simulation. Simulate M new paths of the game under the current controls u⁽ᵏ⁾.
        2. Targets. Evaluate Λⁱ / (2 aᵢ) along each path for every player i, by differentiating the
           realised reward with respect to the player's own control (Solver.targets).
        3. Regression. Fit the network of each player to the damped target
               (1 - ρ) u^{i,(k)} + (ρ / 2 aᵢ) Λⁱ
           by minimizing the mean squared error over the paths, with the player's own observed path as the
           only input (Solver.fit).
    The validation controls are averaged over the later iterations (iterate averaging), which reduces the
    fluctuation from one iteration to the next caused by the regression noise.
    """

    def __init__(self, game, width: int = 32, damping: float = 0.6, steps: int = 1000, batch: int = 1000,
                 lr: float = 1e-3, n_paths: int = 10000, control_variate: bool = True, seed: int = 0):
        """
        Args:
            game: The game (games.base.Game).
            width: Dimension of the summary of the observed path in every control. Default 32.
            damping: ρ, the weight of the new target in the Picard step. Default 0.6.
            steps: Adam steps of each regression. Default 1000.
            batch: Minibatch size of the regression. Default 1000.
            lr: Learning rate of the regression. Default 1e-3.
            n_paths: Number M of training paths, drawn afresh at each iteration. Default 10000.
            control_variate: Whether to subtract the martingale term of control_variate.py from the targets.
                Default True.
            seed: Seed of the network initialisation and of the training paths. Default 0.
        """
        torch.manual_seed(seed)
        self.game = game
        self.damping = damping
        self.steps = steps
        self.batch = batch
        self.lr = lr
        self.controls = [Control(game.observation_dims[i], width) for i in range(game.n_players)]
        self.control_variate = ControlVariate(game) if control_variate else None
        self.n_paths = n_paths
        self.seed = seed
        self.validation = validation_paths(game)
        self.t = torch.arange(game.N, dtype=torch.float32) * game.dt     # the grid t_0, ..., t_{N-1}

    # --------------------------------------------------------------------------
    # Step 1: forward simulation
    # --------------------------------------------------------------------------

    def simulate(self, exogenous: dict, fixed: dict = None):
        """
        Simulates the game on the given paths, by the Euler--Maruyama scheme with the controls given by the
        networks at each step.

        Args:
            exogenous: Exogenous processes of M paths (game.sample).
            fixed: {player: controls [M, N]} for players whose controls are given instead of computed by their
                networks. Solver.targets fixes all of them, to differentiate the rewards with respect to the
                controls. Default none.

        Returns:
            state: The state paths (game.initial_state, filled in).
            controls: List of [M, N] tensors, one per player.
        """
        game = self.game
        M = next(iter(exogenous.values())).shape[0]
        fixed = fixed or {}
        state = game.initial_state(exogenous)
        summaries = [torch.zeros(1, M, control.width) for control in self.controls]
        observations = [game.observe(i, state, exogenous, 0) for i in range(game.n_players)]
        controls = [[] for _ in self.controls]
        with torch.set_grad_enabled(any(u.requires_grad for u in fixed.values())):
            for j in range(game.N):
                u = {}
                for i, control in enumerate(self.controls):
                    if i in fixed:
                        u[i] = fixed[i][:, j]
                    else:
                        u[i] = control(self.t[j].expand(M, 1), observations[i], summaries[i][0]).detach()
                    controls[i].append(u[i])
                game.step(state, exogenous, u, j)
                # Update each summary with the observation increment over [t_j, t_{j+1}].
                for i, control in enumerate(self.controls):
                    new_observation = game.observe(i, state, exogenous, j + 1)
                    if i not in fixed:
                        increment = (new_observation - observations[i]) / math.sqrt(game.dt)
                        summaries[i] = control.gru(increment[:, None], summaries[i])[1].detach()
                    observations[i] = new_observation
        return state, [torch.stack(c, 1) for c in controls]

    # --------------------------------------------------------------------------
    # Step 2: targets
    # --------------------------------------------------------------------------

    def targets(self, exogenous: dict, controls: list) -> list:
        """
        Evaluates Λⁱ / (2 aᵢ) along each path for every player, the quantity inside the conditional
        expectation of the operator Ψ.

        The derivative of the realised reward Rⁱ with respect to uⁱ_t is Gⁱ_t = -2 aᵢ uⁱ_t + Λⁱ_t
        (the first order condition of the note), so Λⁱ / (2 aᵢ) = uⁱ + Gⁱ / (2 aᵢ). In the open loop
        the other players' controls are held fixed as processes, so the game is simulated once with every
        player's controls fixed at their current values. Each Gⁱ is the derivative of Rⁱ with respect to uⁱ on
        that one simulation, by automatic differentiation, in chunks of 5000 paths. game.curvature(i) supplies
        2 aᵢ dt, the scaling of the derivative on the grid.

        Args:
            exogenous: Exogenous processes of the paths.
            controls: Current controls, list of [M, N] tensors.

        Returns:
            List of [M, N] targets, one per player.
        """
        game = self.game
        M = controls[0].shape[0]
        all_targets = [torch.zeros_like(c) for c in controls]
        for start in range(0, M, 5000):
            index = torch.arange(start, min(start + 5000, M))
            part = {key: value[index] for key, value in exogenous.items()}
            fixed = {i: c[index].detach().clone().requires_grad_(True) for i, c in enumerate(controls)}
            state, used = self.simulate(part, fixed)
            for i in range(game.n_players):
                reward = game.reward(i, state, part, used).sum()
                gradient, = torch.autograd.grad(reward, fixed[i], retain_graph=i < game.n_players - 1)
                all_targets[i][index] = (fixed[i] + gradient / game.curvature(i)).detach()
        return all_targets

    # --------------------------------------------------------------------------
    # Step 3: regression
    # --------------------------------------------------------------------------

    def fit(self, exogenous: dict, state: dict, targets: list, damping: float, players=None) -> float:
        """
        Fits the networks to the targets by minimizing a mean squared error.

        For each player i, the loss is the mean over paths and times of

            | 𝒩ⁱ(t_j, Oⁱ_{[0, t_j]}; theta^i) - target^i_j |^2,

        minimized by Adam from the current parameters (warm start). With the control variate, damping times the
        martingale term is subtracted from the target, since the target is already damped by the same factor,
        and the networks ζⁱ are fitted jointly.

        Args:
            exogenous, state: The simulated paths (Solver.simulate).
            targets: List of [M, N] targets, one per player.
            damping: Weight of the martingale term.
            players: Players to fit. Default all.

        Returns:
            The loss at the last step.
        """
        game = self.game
        M = targets[0].shape[0]
        players = range(game.n_players) if players is None else players
        t = self.t.expand(M, game.N)[..., None]
        observations, increments = [], []
        for i in range(game.n_players):
            path = torch.stack([game.observe(i, state, exogenous, j) for j in range(game.N + 1)], 1)
            observations.append(path[:, :-1])
            increments.append((path[:, 1:] - path[:, :-1]) / math.sqrt(game.dt))
        parameters = [p for i in players for p in self.controls[i].parameters()]
        if self.control_variate:
            full_state, martingale_increments = self.control_variate.inputs(state, exogenous, t)
            parameters += self.control_variate.parameters(players)
        optimizer = torch.optim.Adam(parameters, lr=self.lr)
        for _ in range(self.steps):
            index = torch.randint(0, M, (self.batch,))
            loss = 0.0
            for i in players:
                control = self.controls[i]
                target = targets[i][index]
                if self.control_variate:
                    target = target - damping * self.control_variate.term(i, full_state[index], martingale_increments[index])
                prediction = control(t[index], observations[i][index], control.summaries(increments[i][index]))
                loss = loss + ((prediction - target) ** 2).mean()
            optimizer.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(parameters, 5.0)
            optimizer.step()
        return float(loss.detach())

    # --------------------------------------------------------------------------
    # The iteration
    # --------------------------------------------------------------------------

    def run(self, iterations: int, average_from: int = 4, reference: list = None, verbose: bool = True):
        """
        Runs the damped Picard iteration.

        Args:
            iterations: Number K of iterations.
            average_from: First iteration included in the average of the validation controls. Default 4.
            reference: Reference validation controls, list of [M, N] tensors. Default none.
            verbose: Whether to print, at each iteration, the regression loss and, with a reference, the relative
                L2 error of the current and of the averaged controls. Default True.

        Returns:
            controls: The averaged validation controls, list of [M, N] tensors.
            history: Per iteration, the relative L2 error of each player's current controls against reference.
        """
        average, count, history = None, 0, []
        start = time.time()
        for k in range(iterations):
            training = self.game.sample(self.n_paths, 1000 * (self.seed + 1) + k)
            state, controls = self.simulate(training)
            targets = self.targets(training, controls)
            damped = [(1 - self.damping) * u + self.damping * target for u, target in zip(controls, targets)]
            loss = self.fit(training, state, damped, self.damping)
            _, validation = self.simulate(self.validation)
            if k >= average_from:
                count += 1
                average = validation if average is None else [a + (v - a) / count for a, v in zip(average, validation)]
            message = f'iteration {k:2d}  loss {loss:.2e}'
            if reference is not None:
                history.append([relative_l2(v, r) for v, r in zip(validation, reference)])
                message += '  error ' + ' '.join(f'{e:.3f}' for e in history[-1])
                if average is not None:
                    message += '  averaged ' + ' '.join(f'{relative_l2(a, r):.3f}' for a, r in zip(average, reference))
            if verbose:
                print(message + f'  ({time.time() - start:.0f}s)', flush=True)
        return (average or validation), history


def first_order_residual(solver: Solver, i: int, n_paths: int = None) -> float:
    """
    Checks the first order condition of player i at the computed controls.

    On fresh paths simulated under the current controls, a new, independently initialised network is fitted (with
    twice the solver's steps) to player i's undamped target Λⁱ / (2 aᵢ). At an open-loop equilibrium this
    regression reproduces uⁱ, so the relative L2 distance between the two on the validation paths is zero up to
    regression error. The solver is left unchanged.

    Args:
        solver: The solver after Solver.run.
        i: The player.
        n_paths: Number of fresh paths. Default: the solver's number of training paths.

    Returns:
        The relative L2 distance between the independent regression and the current control.
    """
    game = solver.game
    exogenous = game.sample(n_paths or solver.n_paths, 23 + i)
    state, controls = solver.simulate(exogenous)
    target = solver.targets(exogenous, controls)[i]
    saved_control, saved_steps = solver.controls[i], solver.steps
    saved_zetas = copy.deepcopy(solver.control_variate.zetas) if solver.control_variate else None
    try:
        solver.controls[i] = Control(game.observation_dims[i], saved_control.width)
        solver.steps = 2 * saved_steps
        targets = [target if j == i else controls[j] for j in range(game.n_players)]
        solver.fit(exogenous, state, targets, 1.0, players=[i])
        _, fresh = solver.simulate(solver.validation)
    finally:
        solver.controls[i], solver.steps = saved_control, saved_steps
        if solver.control_variate:
            solver.control_variate.zetas = saved_zetas
    _, current = solver.simulate(solver.validation)
    return relative_l2(fresh[i], current[i])
