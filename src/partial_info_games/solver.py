# Gradient play
# ==============================================================================

def gradient_play(solver: Solver, iterations: int, steps: int = 200, lr: float = 1e-4, closed: bool = True,
                  reference: list = None, log=report):
    """
    Gradient play on the realised costs, an alternative solver for closed-loop equilibria.

    At each step, every player takes an Adam step on its own expected cost, estimated on a minibatch of
    simulated paths, with respect to its own network parameters. All players step together. A fixed point
    is a Nash equilibrium within the network class. In the closed loop, the game is simulated with every
    network in the graph, so player i's gradient includes the response of the other players' controls to
    its actions through their observations. In the open loop, the other players' controls are detached.

    Args:
        solver: A Solver whose controls are the starting point (for example after Solver.run).
        iterations: Number of iterations; each takes `steps` Adam steps and logs one line.
        steps: Adam steps per iteration. Default 200.
        lr: Learning rate. Default 1e-4.
        closed: Closed loop (default) or open loop.
        reference: Reference validation controls for the error log. Default none.
        log: Function that receives one progress line per iteration.

    Returns:
        controls: The validation controls averaged over the second half of the iterations.
        history: Per iteration, the relative L2 error of each player against reference.
    """
    game = solver.game
    M = next(iter(solver.noise.values())).shape[0]
    players = range(game.n_players)
    optimizers = [torch.optim.Adam(c.parameters(), lr=lr) for c in solver.controls]
    average = RunningAverage()
    history = []
    start = time.time()
    for k in range(iterations):
        for _ in range(steps):
            part = subset(solver.noise, torch.randint(0, M, (solver.batch,)))
            if closed:
                state, controls, _ = solver.simulate(part, live=set(players))
                costs = [game.cost(i, state, part, controls).mean() for i in players]
                gradients = [torch.autograd.grad(costs[i], list(solver.controls[i].parameters()),
                                                 retain_graph=i < game.n_players - 1) for i in players]
            else:
                gradients = []
                for i in players:
                    state, controls, _ = solver.simulate(part, live={i})
                    cost = game.cost(i, state, part, controls).mean()
                    gradients.append(torch.autograd.grad(cost, list(solver.controls[i].parameters())))
            for control, optimizer, gradient in zip(solver.controls, optimizers, gradients):
                for parameter, g in zip(control.parameters(), gradient):
                    parameter.grad = g
                nn.utils.clip_grad_norm_(control.parameters(), 5.0)
                optimizer.step()
        _, validation, _ = solver.simulate(solver.validation)
        if k >= iterations // 2:
            average.add(validation)
        message = f'gradient play iteration {k:2d}'
        if reference is not None:
            history.append([relative_l2(v, r) for v, r in zip(validation, reference)])
            message += '  error ' + format_errors(validation, reference)
        log(message + f'  ({time.time() - start:.0f}s)')
    return (average.value or validation), history


# ==============================================================================
# Linear-strategy baseline
# ==============================================================================

def linear_equilibrium(solver: Solver, iterations: int = 30, average_from: int = 15, reference: list = None, log=report):
    """
    The damped Picard iteration restricted to controls linear in the observed path.

    The regression of Solver.fit is replaced by ordinary least squares at each t_j on the features
    (1, O^i_{t_j}, all increments of O^i before t_j). This gives the best linear predictor of the target,
    and the iteration converges to the equilibrium among strategies linear in the observed path, a
    baseline for the learned equilibrium in games where the conditional expectation is nonlinear.

    Args:
        solver: A Solver, used for its game, paths, damping and targets.
        iterations: Number of iterations. Default 30.
        average_from: First iteration included in the average of the validation controls. Default 15.
        reference: Reference validation controls for the error log. Default none.
        log: Function that receives one progress line per iteration.

    Returns:
        The averaged validation controls, list of [M, N] tensors.
    """
    game = solver.game
    N = game.N
    players = range(game.n_players)

    def simulate(noise, coefficients):
        """Simulates the game under the linear controls; returns the controls and the features at each step."""
        M = next(iter(noise.values())).shape[0]
        state = game.initial_state(noise)
        controls = [torch.zeros(M, N) for _ in players]
        features = [[None] * N for _ in players]
        past = [[] for _ in players]
        for j in range(N):
            u = {}
            for i in players:
                features[i][j] = torch.cat([torch.ones(M, 1), game.observe(i, state, noise, j)] + past[i], 1)
                u[i] = features[i][j] @ coefficients[i][j] if coefficients else torch.zeros(M)
                controls[i][:, j] = u[i]
            game.step(state, noise, u, j)
            for i in players:
                if game.increment_dims[i] > 0:
                    past[i].append(game.increment(i, state, noise, j))
        return controls, features

    def least_squares(features, target):
        """Least-squares coefficients in float64, with a rank cutoff because the features can be collinear."""
        features, target = features.cpu().double(), target.cpu().double()[:, None]
        solution = torch.linalg.lstsq(features, target, rcond=1e-6, driver='gelsd').solution
        return solution[:, 0].float().to(torch.get_default_device())

    coefficients = None
    average = RunningAverage()
    for k in range(iterations):
        controls, features = simulate(solver.noise, coefficients)
        targets = solver.targets(solver.noise, controls)
        damped = [(1 - solver.damping) * u + solver.damping * target for u, target in zip(controls, targets)]
        coefficients = [[least_squares(features[i][j], damped[i][:, j]) for j in range(N)] for i in players]
        validation, _ = simulate(solver.validation, coefficients)
        if k >= average_from:
            average.add(validation)
        if reference is not None:
            log(f'linear iteration {k:2d}  error ' + format_errors(average.value or validation, reference))
    return average.value or validation


# ==============================================================================
# First order condition check
# ==============================================================================

def first_order_residual(solver: Solver, i: int, n_paths: int = None) -> float:
    """
    Checks the first order condition of player i at the computed controls.

    On fresh paths simulated under the current controls, a new, independently initialised network is
    fitted (with twice the solver's steps) to player i's undamped open-loop target Lambda^i / (2 a_i).
    At an open-loop equilibrium this regression reproduces u^i, so the relative L2 distance between the
    two on the validation paths is zero up to regression error. The solver is left unchanged.

    Args:
        solver: The solver after Solver.run.
        i: The player.
        n_paths: Number of fresh paths. Default: the solver's number of training paths.

    Returns:
        The relative L2 distance between the independent regression and the current control.
    """
    game = solver.game
    noise = game.sample(n_paths or next(iter(solver.noise.values())).shape[0], 23 + i)
    state, controls, increments = solver.simulate(noise)
    target = solver.targets(noise, controls)[i]
    saved_control, saved_steps = solver.controls[i], solver.steps
    saved_zeta = copy.deepcopy(solver.zetas[i]) if solver.control_variate else None
    try:
        solver.controls[i] = Control(game.observation_dims[i], game.increment_dims[i], saved_control.width or 32)
        solver.steps = 2 * saved_steps
        targets = [target if j == i else controls[j] for j in range(game.n_players)]
        solver.fit(noise, state, increments, targets, 1.0, players=[i])
        _, fresh, _ = solver.simulate(solver.validation)
    finally:
        solver.controls[i], solver.steps = saved_control, saved_steps
        if solver.control_variate:
            solver.zetas[i] = saved_zeta
    _, current, _ = solver.simulate(solver.validation)
    return relative_l2(fresh[i], current[i])
